#!/usr/bin/env python3
"""Import the complete upstream Kodi Android application layer as an isolated Android library."""
from pathlib import Path
import shutil
import sys
import xml.etree.ElementTree as ET

if len(sys.argv) != 2:
    raise SystemExit("usage: import-kodi-android.py <Kodi source checkout>")

source = Path(sys.argv[1]) / "tools/android/packaging/xbmc"
destination = Path("kodi/src/main")
if not (source / "AndroidManifest.xml.in").is_file():
    raise SystemExit(f"Kodi Android packaging source not found: {source}")

replacements = {
    "@APP_PACKAGE@": "org.xbmc.kodi",
    "@APP_NAME@": "Kodi",
    "@APP_NAME_LC@": "kodi",
    "@APP_VERSION_CODE_ANDROID@": "1",
    "@APP_VERSION@": "1.0",
}
java_root = destination / "java"
if java_root.exists():
    shutil.rmtree(java_root)
java_root.mkdir(parents=True)
java_count = 0
for template in sorted((source / "src").rglob("*.java.in")):
    relative = template.relative_to(source / "src")
    output = java_root / "org" / "xbmc" / "kodi" / relative.with_suffix("")
    output.parent.mkdir(parents=True, exist_ok=True)
    content = template.read_text(encoding="utf-8")
    for old, new in replacements.items():
        content = content.replace(old, new)
    if "@APP_" in content:
        raise SystemExit(f"Unresolved Kodi Java template token in {template}")
    output.write_text(content, encoding="utf-8")
    java_count += 1

res_root = destination / "res"
if res_root.exists():
    shutil.rmtree(res_root)
shutil.copytree(source / "res", res_root)
(res_root / "values").mkdir(parents=True, exist_ok=True)
(res_root / "xml").mkdir(parents=True, exist_ok=True)
for template, output in (
    (source / "strings.xml.in", res_root / "values/strings.xml"),
    (source / "colors.xml.in", res_root / "values/colors.xml"),
    (source / "searchable.xml.in", res_root / "xml/searchable.xml"),
):
    content = template.read_text(encoding="utf-8")
    for old, new in replacements.items():
        content = content.replace(old, new)
    if "@APP_" in content:
        raise SystemExit(f"Unresolved Kodi resource token in {template}")
    output.write_text(content, encoding="utf-8")

# Splash artwork is generated by Kodi's packaging build, not stored in the source tree.
(res_root / "layout/activity_splash.xml").write_text("""<?xml version="1.0" encoding="utf-8"?>
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@android:color/black">
    <LinearLayout
        android:layout_width="match_parent"
        android:layout_height="wrap_content"
        android:layout_gravity="center"
        android:gravity="center"
        android:orientation="vertical"
        android:padding="24dp">
        <TextView
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:text="@string/app_name"
            android:textColor="@android:color/white"
            android:textSize="24sp"
            android:textStyle="bold" />
        <ProgressBar
            android:id="@+id/progressBar1"
            style="?android:attr/progressBarStyleHorizontal"
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:layout_marginTop="18dp"
            android:progressDrawable="@drawable/progresscolor" />
        <TextView
            android:id="@+id/textView1"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginTop="12dp"
            android:textColor="@android:color/white"
            android:textSize="14sp" />
    </LinearLayout>
</FrameLayout>
""", encoding="utf-8")

ET.register_namespace("android", "http://schemas.android.com/apk/res/android")
ET.register_namespace("tools", "http://schemas.android.com/tools")
android = "{http://schemas.android.com/apk/res/android}"
manifest_text = (source / "AndroidManifest.xml.in").read_text(encoding="utf-8")
for old, new in replacements.items():
    manifest_text = manifest_text.replace(old, new)
if "@APP_" in manifest_text:
    raise SystemExit("Unresolved Kodi manifest template token")
tree = ET.ElementTree(ET.fromstring(manifest_text))
root = tree.getroot()
for attribute in ("installLocation", "versionCode", "versionName"):
    root.attrib.pop(android + attribute, None)
application = root.find("application")
if application is None:
    raise SystemExit("Kodi Android manifest has no application element")
# Fermata owns package identity; merge Kodi's components and Android permissions.
for attribute in ("banner", "hasCode", "icon", "label", "logo",
                  "requestLegacyExternalStorage", "enableOnBackInvokedCallback"):
    application.attrib.pop(android + attribute, None)
for activity in list(application.findall("activity")):
    name = activity.attrib.get(android + "name", "")
    if name.endswith(".Splash"):
        for child in list(activity):
            if child.tag == "intent-filter":
                activity.remove(child)
        activity.set(android + "exported", "false")
    elif name.endswith(".Main"):
        activity.set(android + "exported", "false")
manifest_path = destination / "AndroidManifest.xml"
manifest_path.parent.mkdir(parents=True, exist_ok=True)
ET.indent(tree, space="    ")
tree.write(manifest_path, encoding="utf-8", xml_declaration=True)
print(f"Imported {java_count} upstream Kodi Java classes, resources and manifest components.")
